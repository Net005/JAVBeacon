// migratePostgres applies postgresSchemaDDL and then runs the same
// one-time data migrations SQLite's migrate() runs, in the same order.
// Those functions (removeScheduledDownloads, migrateReleaseIdentity,
// backfillReleaseMetadata, cleanupStoredReleaseText,
// backfillLocalAvailableNotifications, normalizeJavLibraryURLs) are plain
// methods on *SQLite, not
// SQLite-specific despite the type name (see that type's doc comment) -
// every query they run is either already portable or was made portable in
// DB Phase 5 (see store.go's cleanupStoredReleaseText and
// removeScheduledDownloads for the two places that needed a small,
// targeted change), so they are reused here unchanged rather than
// duplicated. On a fresh database every one of them affects zero rows and
// exists mainly to leave the same settings completion flags
// (release_identity_dedup_v1, metadata_text_cleanup_v1,
// local_available_notifications_v1) set that a fresh SQLite install would
// have, so the two engines' settings tables never observably disagree
// about what "up to date" means.
func (s *SQLite) migratePostgres(ctx context.Context, report MigrationProgressFunc) error {
	statements := make([]string, 0)
	for _, statement := range strings.Split(postgresSchemaDDL, ";\n") {
		statement = strings.TrimSpace(statement)
		if statement != "" {
			statements = append(statements, statement)
		}
	}
	for current, statement := range statements {
		reportMigration(report, MigrationProgress{Phase: "Database schema", Step: describePostgresMigrationStatement(statement), Current: current + 1, Total: len(statements)})
		if _, err := s.db.ExecContext(ctx, statement); err != nil {
			return err
		}
	}
	reportMigration(report, MigrationProgress{Phase: "Data compatibility", Step: "Applying existing-installation migrations"})
	// Incremental addition for a PostgreSQL database created before this
	// column existed (TODO-2.0's "Added to StashApp (with date)"). Unlike
	// SQLite, PostgreSQL supports IF NOT EXISTS on ADD COLUMN directly, so
	// this needs no duplicate-column error tolerance.
	if _, err := s.db.ExecContext(ctx, `ALTER TABLE releases ADD COLUMN IF NOT EXISTS stash_added_at TIMESTAMPTZ`); err != nil {
		return err
	}
	if _, err := s.db.ExecContext(ctx, `ALTER TABLE releases ADD COLUMN IF NOT EXISTS stash_release_date TEXT NOT NULL DEFAULT ''`); err != nil {
		return err
	}
	// Incremental addition for a PostgreSQL database created before
	// per-pipeline-step timeouts existed (each step can now override the
	// settings-wide default step timeout individually).
	if _, err := s.db.ExecContext(ctx, `ALTER TABLE pipeline_steps ADD COLUMN IF NOT EXISTS timeout_seconds INTEGER NOT NULL DEFAULT 0`); err != nil {
		return err
	}
	// Incremental addition for a PostgreSQL database created before the
	// Missing Library Files "allow non-preferred filenames" fallback chain
	// and manual Force download override both started recording a
	// structured, filterable flag on the resulting download (TODO-2.0
	// Task A) instead of only free text inside match_reason.
	if _, err := s.db.ExecContext(ctx, `ALTER TABLE downloads ADD COLUMN IF NOT EXISTS filename_pattern_excluded INTEGER NOT NULL DEFAULT 0`); err != nil {
		return err
	}
	if _, err := s.db.ExecContext(ctx, `ALTER TABLE downloads ADD COLUMN IF NOT EXISTS seen_complete BIGINT NOT NULL DEFAULT 0`); err != nil {
		return err
	}
	// Incremental addition for a PostgreSQL database created before the
	// "allow non-preferred filenames" override became a persistent
	// per-release setting instead of a one-off flag on a single Missing
	// Library Files apply run.
	if _, err := s.db.ExecContext(ctx, `ALTER TABLE releases ADD COLUMN IF NOT EXISTS allow_non_preferred_filenames INTEGER NOT NULL DEFAULT 0`); err != nil {
		return err
	}
	// Incremental addition for a PostgreSQL database created before the
	// Release Library Conditions dialog gained the "O Count"/"Last O Count
	// Date"/"Last Played" fields, best-effort-populated from a matched
	// StashApp scene alongside stash_release_date.
	for _, statement := range []string{
		`ALTER TABLE sites ADD COLUMN IF NOT EXISTS watchlist INTEGER NOT NULL DEFAULT 0`,
		`ALTER TABLE sites ADD COLUMN IF NOT EXISTS auto_monitor_future INTEGER NOT NULL DEFAULT 0`,
		`ALTER TABLE releases ADD COLUMN IF NOT EXISTS watchlist INTEGER NOT NULL DEFAULT 0`,
		`ALTER TABLE releases ADD COLUMN IF NOT EXISTS o_counter INTEGER NOT NULL DEFAULT 0`,
		`ALTER TABLE releases ADD COLUMN IF NOT EXISTS play_count INTEGER NOT NULL DEFAULT 0`,
		`ALTER TABLE releases ADD COLUMN IF NOT EXISTS last_played_at TEXT NOT NULL DEFAULT ''`,
		`ALTER TABLE releases ADD COLUMN IF NOT EXISTS last_o_count_at TEXT NOT NULL DEFAULT ''`,
		`ALTER TABLE releases ADD COLUMN IF NOT EXISTS screenshots_checked_at TIMESTAMPTZ`,
		`ALTER TABLE releases ADD COLUMN IF NOT EXISTS watchlist_at TIMESTAMPTZ`,
		`ALTER TABLE releases ADD COLUMN IF NOT EXISTS stash_created_at TIMESTAMPTZ`,
		`ALTER TABLE releases ADD COLUMN IF NOT EXISTS is_preferred INTEGER NOT NULL DEFAULT 1`,
		`ALTER TABLE releases ADD COLUMN IF NOT EXISTS monitor_reason TEXT NOT NULL DEFAULT ''`,
		`ALTER TABLE releases ADD COLUMN IF NOT EXISTS monitor_site_id BIGINT NOT NULL DEFAULT 0`,
		`ALTER TABLE releases ADD COLUMN IF NOT EXISTS ignore_local_force_download INTEGER NOT NULL DEFAULT 0`,
		`ALTER TABLE job_history ADD COLUMN IF NOT EXISTS title TEXT NOT NULL DEFAULT ''`,
		`ALTER TABLE job_history ADD COLUMN IF NOT EXISTS scheduled INTEGER NOT NULL DEFAULT 0`,
		`ALTER TABLE job_history ADD COLUMN IF NOT EXISTS site_count INTEGER NOT NULL DEFAULT 0`,
	} {
		if _, err := s.db.ExecContext(ctx, statement); err != nil {
			return err
		}
	}
	if err := s.migrateWatchlistNaming(ctx); err != nil {
		return err
	}
	for _, statement := range []string{
		`CREATE INDEX IF NOT EXISTS idx_releases_preferred ON releases(is_preferred,id)`,
		`CREATE INDEX IF NOT EXISTS idx_releases_local_created ON releases(is_local,stash_created_at DESC,id DESC)`,
		`CREATE INDEX IF NOT EXISTS idx_releases_watchlist_date ON releases(watchlist,watchlist_at DESC,id DESC)`,
	} {
		if _, err := s.db.ExecContext(ctx, statement); err != nil {
			return err
		}
	}
	// Backfill watchlist_at for releases already marked Watchlist before this
	// column existed, so the Release Library's Watchlist-tab "when marked as
	// watchlist" sort has something to sort by right after upgrade instead of
	// every pre-existing Watchlist release tying at NULL. updated_at is the
	// closest available approximation of when watchlist was last toggled true
	// for these rows.
	if _, err := s.db.ExecContext(ctx, `UPDATE releases SET watchlist_at=updated_at WHERE watchlist=1 AND watchlist_at IS NULL`); err != nil {
		return err
	}
	// Backfill stash_created_at the same way the SQLite migration does - see
	// its comment for why stash_added_at is the closest available
	// approximation until the next StashApp sync overwrites it.
	if _, err := s.db.ExecContext(ctx, `UPDATE releases SET stash_created_at=stash_added_at WHERE is_local=1 AND stash_created_at IS NULL AND stash_added_at IS NOT NULL`); err != nil {
		return err
	}
	if err := s.removeScheduledDownloads(); err != nil {
		return err
	}
	if err := s.migrateSiteMonitoringRedesign(ctx); err != nil {
		return err
	}
	if err := s.cleanupStoredReleaseText(ctx); err != nil {
		return err
	}
	if err := s.backfillReleaseMetadata(ctx); err != nil {
		return err
	}
	if err := s.migrateReleaseIdentity(ctx); err != nil {
		return err
	}
	if err := s.migrateNormalizedReleaseMetadata(ctx); err != nil {
		return err
	}
	if _, err := s.db.ExecContext(ctx, `UPDATE sites SET download_mode='future' WHERE download=1 AND download_mode=''`); err != nil {
		return err
	}
	if err := s.backfillLocalAvailableNotifications(ctx); err != nil {
		return err
	}
	if err := s.normalizeJavLibraryURLs(); err != nil {
		return err
	}
	return s.normalizeReleaseTimestamps(ctx)
}

// OpenPostgresStore opens a fully migrated PostgreSQL-backed Store: it
// opens a connection pool via OpenPostgres (DB Phase 3's driver/pool
// setup, including the DB Phase 5 query-rewriting connector - see
// postgres_rewrite.go), applies postgresSchemaDDL and the one-time data
// migrations via migratePostgres, and returns the same *SQLite type
// OpenSQLite returns (see that type's doc comment for why that is not a
// naming mistake). If migration fails, the pool is closed before
// returning so a caller cannot end up holding a half-migrated connection.
func OpenPostgresStore(ctx context.Context, c PostgresConfig) (*SQLite, error) {
	return OpenPostgresStoreWithProgress(ctx, c, nil)
}

// OpenPostgresStoreWithProgress is OpenPostgresStore with a read-only progress
// callback for startup and recovery UIs. The callback is never allowed to
// affect migration behavior and receives no credentials or row data.
func OpenPostgresStoreWithProgress(
	ctx context.Context,
	c PostgresConfig,
	report MigrationProgressFunc,
) (*SQLite, error) {
	reportMigration(report, MigrationProgress{
		Phase: "Database connection",
		Step:  "Connecting to PostgreSQL",
	})

	// Only the connection/ping phase gets a short timeout.
	// Migrations and backfills may legitimately take much longer.
	connectCtx, cancel := context.WithTimeout(ctx, 30*time.Second)
	db, err := OpenPostgres(connectCtx, c)
	cancel()

	if err != nil {
		return nil, err
	}

	s := &SQLite{
		db:      db,
		dialect: PostgresDialect{},
	}

	// Use the original context for migrations, not connectCtx.
	if err := s.migratePostgres(ctx, report); err != nil {
		db.Close()
		return nil, err
	}

	reportMigration(report, MigrationProgress{
		Phase: "Release preferences",
		Step:  "Updating saved ignore-tag and title filters",
	})

	// This may perform the large releases UPDATE and must not inherit
	// the 30-second connection deadline.
	if err := s.initializeReleasePreferences(ctx); err != nil {
		db.Close()
		return nil, err
	}

	reportMigration(report, MigrationProgress{
		Phase:   "Database ready",
		Step:    "Database migrations completed",
		Current: 1,
		Total:   1,
	})

	return s, nil
}
