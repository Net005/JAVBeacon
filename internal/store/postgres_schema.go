// This file is DB Phase 5's PostgreSQL schema/migration counterpart to
// migrate() in store.go. It intentionally does not try to replay SQLite's
// migrate() history of incremental "CREATE TABLE IF NOT EXISTS" plus
// tolerant "ALTER TABLE ADD COLUMN" statements - PostgreSQL only exists as
// a supported runtime target starting with this phase, so there is no
// pre-existing PostgreSQL installation whose older schema needs upgrading
// (unlike SQLite, which has real installs going back to before several of
// those columns existed). postgresSchemaDDL instead states the single,
// current, cumulative schema directly - the same end state SQLite's
// migrate() reaches after every ALTER TABLE runs - which is what DB Phase
// 5's "empty PostgreSQL -> latest schema" test scenario calls for. Should
// a later phase need to evolve the PostgreSQL schema further, add
// incremental ALTER TABLE statements here the same way SQLite's migrate()
// does; this baseline does not need to be (and should not be) rewritten
// to simulate history that never happened for PostgreSQL.
//
// Column types intentionally differ from a "native" PostgreSQL schema in
// two ways, both to keep every query string in this package (store.go)
// engine-agnostic rather than needing a second, parallel set of queries:
//
//  1. Every boolean-shaped column (enabled, notify, released, is_local,
//     ...) is a plain INTEGER storing 0/1, exactly like SQLite, rather
//     than PostgreSQL's native BOOLEAN. This keeps every literal
//     comparison already in store.go's query strings ("WHERE
//     download=1", "SET is_local=?", ...) valid unmodified on both
//     engines; postgres_rewrite.go's convertBoolArgs converts a Go bool
//     argument to 0/1 at the driver layer for exactly this reason, and
//     scanning an INTEGER 0/1 back into a Go bool works natively on both
//     engines without help. See that file's doc comment for the full
//     rationale and the empirical check (a Go bool cannot be bound
//     directly against a PostgreSQL INTEGER column - pgx rejects it -
//     which is why this conversion exists at all).
//  2. Autoincrementing primary keys use PostgreSQL's identity-column
//     syntax (GENERATED BY DEFAULT AS IDENTITY) rather than SQLite's
//     INTEGER PRIMARY KEY rowid aliasing - the two are not textually
//     compatible, but Dialect.InsertReturningID (dialect.go) already
//     abstracts the one place that distinction is visible to callers
//     (PostgreSQL needs INSERT...RETURNING id instead of
//     Result.LastInsertId()), so no other change is needed. Only the 9
//     tables actually relying on an application-assigned/generated id
//     (sites, releases, filter_presets, job_history, downloads,
//     path_mappings, pipeline_steps, pipeline_logs, notifications) use
//     it; tables with a fixed, foreign-key-derived, or composite primary
//     key (users, user_preferences, sessions, settings, watchlist_sync,
//     release_actresses, release_tags, release_sites, pipeline_runs) do
//     not.
//
// DATETIME (SQLite's storage class for time.Time - modernc.org/sqlite
// marshals it as text) becomes TIMESTAMPTZ, PostgreSQL's standard type
// for representing an instant - every timestamp this package writes is
// already time.Now().UTC(), so this is a direct, lossless mapping.
//
// CREATE TABLE/INDEX use IF NOT EXISTS throughout, exactly like SQLite's
// migrate(), so this function is safe to call unconditionally on every
// startup, matching the pattern that function already established -
// PostgreSQL has supported CREATE INDEX IF NOT EXISTS since 9.5 and ADD
// COLUMN IF NOT EXISTS since 9.6, both long predating the PostgreSQL 18
// baseline DB Phase 1A targets.
